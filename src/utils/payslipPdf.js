/**
 * Zero-dependency valid PDF 1.4 generator for KNOOVIQ Monthly Payslips.
 * Keeps output deterministic, ASCII-safe (Rs. for INR), and printable on A4.
 */
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

function pdfEscape(str) {
  return String(str ?? '')
    .replace(/[^\x20-\x7E]/g, ' ')
    .replaceAll('\\', '\\\\')
    .replaceAll('(', '\\(')
    .replaceAll(')', '\\)');
}

function formatRs(paise) {
  const num = (Number(paise || 0) / 100).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  return `Rs. ${num}`;
}

export function generatePayslipPdf(record) {
  const monthName = MONTHS[(Number(record.month) || 1) - 1] || String(record.month);
  const periodLabel = `${monthName} ${record.year}`;
  const cmds = [];

  const text = (x, y, str, size = 10, bold = false, rgb = [0.07, 0.07, 0.07]) => {
    cmds.push(`${rgb[0]} ${rgb[1]} ${rgb[2]} rg`);
    cmds.push(`BT /${bold ? 'F2' : 'F1'} ${size} Tf ${x} ${y} Td (${pdfEscape(str)}) Tj ET`);
  };
  const rect = (x, y, w, h, fillRgb = null, strokeRgb = null) => {
    if (fillRgb) cmds.push(`${fillRgb[0]} ${fillRgb[1]} ${fillRgb[2]} rg`);
    if (strokeRgb) cmds.push(`${strokeRgb[0]} ${strokeRgb[1]} ${strokeRgb[2]} RG 0.8 w`);
    cmds.push(`${x} ${y} ${w} ${h} re ${fillRgb && strokeRgb ? 'B' : fillRgb ? 'f' : 'S'}`);
  };
  const line = (x1, y1, x2, y2, rgb = [0.85, 0.9, 0.97]) => {
    cmds.push(`${rgb[0]} ${rgb[1]} ${rgb[2]} RG 0.8 w ${x1} ${y1} m ${x2} ${y2} l S`);
  };

  // Page border & header banner
  rect(40, 740, 515, 65, [0.95, 0.97, 1], [0.02, 0.38, 0.91]);
  text(58, 780, 'KNOOVIQ INDUSTRIES PVT LTD', 16, true, [0.0, 0.18, 0.48]);
  text(58, 760, 'Monthly Salary Payslip', 11, true, [0.02, 0.38, 0.91]);
  text(400, 770, `Pay Period: ${periodLabel}`, 10, true, [0.0, 0.18, 0.48]);

  // Employee Details Box
  rect(40, 625, 515, 100, [1, 1, 1], [0.85, 0.9, 0.97]);
  text(56, 705, 'EMPLOYEE INFORMATION', 9, true, [0.02, 0.38, 0.91]);
  line(40, 697, 555, 697);
  text(56, 678, `Employee Name: ${record.employee_name}`, 10, true);
  text(310, 678, `Employee ID: ${record.employee_code}`, 10, true);
  text(56, 658, `Department: ${record.department_name || '-'}`, 10);
  text(310, 658, `Designation: ${record.designation || '-'}`, 10);
  text(56, 638, `Bank Account: ${record.bank_name ? `${record.bank_name} (${record.account_number_masked || 'Not registered'})` : 'Not registered'}`, 10);
  text(310, 638, `Payment Status: ${record.payment_status || 'PENDING'}`, 10, true);

  // Attendance & Working Days Box
  rect(40, 525, 515, 85, [1, 1, 1], [0.85, 0.9, 0.97]);
  text(56, 590, 'ATTENDANCE SUMMARY (FIXED 30 WORKING DAYS)', 9, true, [0.02, 0.38, 0.91]);
  line(40, 582, 555, 582);
  text(56, 560, `Working Days: ${record.working_days}`, 10, true);
  text(225, 560, `Present Days: ${Number(record.present_days)}`, 10, true, [0.09, 0.52, 0.25]);
  text(395, 560, `Absent Days: ${Number(record.absent_days)}`, 10, true, [0.78, 0.13, 0.24]);
  text(56, 540, `Daily Salary (Monthly / 30): ${formatRs(record.daily_salary_paise)}`, 10);

  // Salary Calculation Table
  rect(40, 355, 515, 155, [1, 1, 1], [0.85, 0.9, 0.97]);
  rect(40, 482, 515, 28, [0.95, 0.97, 1], [0.85, 0.9, 0.97]);
  text(56, 492, 'SALARY COMPONENT', 9, true, [0.0, 0.18, 0.48]);
  text(420, 492, 'AMOUNT (INR)', 9, true, [0.0, 0.18, 0.48]);

  text(56, 458, 'Monthly Base Salary (30 Days)', 10);
  text(420, 458, formatRs(record.monthly_salary_paise), 10, true);
  line(40, 444, 555, 444);

  text(56, 424, `Absent Day Deduction (${Number(record.absent_days)} day(s) x ${formatRs(record.daily_salary_paise)})`, 10);
  text(420, 424, `- ${formatRs(record.absent_deduction_paise)}`, 10, true, [0.78, 0.13, 0.24]);
  line(40, 408, 555, 408);

  rect(40, 355, 515, 48, [0.02, 0.38, 0.91], [0.02, 0.38, 0.91]);
  text(56, 374, 'FINAL PAYABLE SALARY', 12, true, [1, 1, 1]);
  text(410, 374, formatRs(record.final_payable_paise), 12, true, [1, 1, 1]);

  // Payment reference & footer
  if (record.provider_utr || record.provider_payout_id) {
    text(56, 328, `Bank Transfer Reference / UTR: ${record.provider_utr || record.provider_payout_id}`, 9, false, [0.25, 0.25, 0.25]);
  }
  text(56, 308, `Payslip ID: PAY-${record.year}${String(record.month).padStart(2, '0')}-${record.id}   |   Generated by KNOOVIQ Payroll System`, 8.5, false, [0.35, 0.35, 0.35]);
  text(56, 292, 'This is a computer-generated payslip and does not require a physical signature.', 8.5, false, [0.45, 0.45, 0.45]);

  const stream = cmds.join('\n');
  const objects = [
    '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
    '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
    '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >> endobj',
    '4 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj',
    '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >> endobj',
    `6 0 obj << /Length ${Buffer.byteLength(stream, 'utf8')} >> stream\n${stream}\nendstream endobj`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (const obj of objects) {
    offsets.push(Buffer.byteLength(pdf, 'utf8'));
    pdf += `${obj}\n`;
  }
  const xrefStart = Buffer.byteLength(pdf, 'utf8');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;
  return Buffer.from(pdf, 'utf8');
}
